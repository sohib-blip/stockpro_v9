// Pure helpers for scripts/dump-schema-snapshot.mjs (no network, no file system).

export const SECTION_TITLES = {
  10: "Schemas",
  20: "Extensions",
  30: "Enum types",
  31: "Domains",
  40: "Sequences",
  50: "Tables",
  55: "Primary keys, unique and check constraints",
  60: "Indexes",
  65: "Sequence ownership",
  70: "Functions and procedures",
  75: "Views",
  76: "Materialized views",
  80: "Foreign keys",
  85: "Triggers",
  90: "Row level security",
  92: "Policies",
  95: "Schema privileges",
  96: "Table and view privileges",
  97: "Function privileges",
  98: "Default privileges",
  99: "Comments",
};

// One statement per line, no blank line in between.
const COMPACT_SECTIONS = new Set([90, 95, 96, 97, 98]);

const MIGRATION_FILE = /^(\d{8,14})_[a-z0-9_]+\.sql$/;

/** Latest migration file name, ordered like the Supabase CLI (by version, then name). */
export function latestMigration(fileNames) {
  const migrations = fileNames.filter((name) => MIGRATION_FILE.test(name));
  if (migrations.length === 0) return null;
  return migrations
    .map((name) => ({ name, version: name.match(MIGRATION_FILE)[1].padEnd(14, "0") }))
    .sort((a, b) => a.version.localeCompare(b.version) || a.name.localeCompare(b.name))
    .at(-1).name;
}

/** Reads the "Last migration" line written in a snapshot header. */
export function snapshotLastMigration(snapshotText) {
  const match = snapshotText.match(/^-- Last migration reflected: (\S+)$/m);
  return match ? match[1] : null;
}

/** Turns the catalog rows into the snapshot file text. */
export function buildSchemaSnapshot({ rows, projectName, generatedOn, lastMigration }) {
  if (!Array.isArray(rows) || rows.length === 0) {
    throw new Error("The catalog query returned no rows: refusing to write an empty snapshot.");
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(generatedOn)) {
    throw new Error(`Invalid snapshot date: ${generatedOn}`);
  }

  const sorted = rows
    .map((row) => {
      const section = Number(row.section);
      if (!SECTION_TITLES[section] || typeof row.ddl !== "string" || typeof row.sort_key !== "string") {
        throw new Error(`Unexpected catalog row: ${JSON.stringify(row).slice(0, 200)}`);
      }
      return { section, sortKey: row.sort_key, ddl: row.ddl.replace(/\r\n/g, "\n").trimEnd() };
    })
    // Byte order, so the file is identical whatever the machine locale.
    .sort((a, b) => a.section - b.section || (a.sortKey < b.sortKey ? -1 : a.sortKey > b.sortKey ? 1 : 0));

  const counts = new Map();
  for (const row of sorted) counts.set(row.section, (counts.get(row.section) ?? 0) + 1);

  const header = [
    "-- StockPro database schema snapshot",
    "-- Generated by scripts/dump-schema-snapshot.mjs. Do not edit by hand: regenerate it (see supabase/schema/README.md).",
    `-- Source project: ${projectName}`,
    `-- Generated on: ${generatedOn}`,
    `-- Last migration reflected: ${lastMigration ?? "none"}`,
    "-- Scope: schemas public and private (structure only, no data). Supabase-managed schemas",
    "-- (auth, storage, realtime, vault, extensions, graphql) are left out.",
    "--",
    "-- Contents:",
    ...[...counts.entries()].map(([section, count]) => `--   ${SECTION_TITLES[section]}: ${count}`),
    "",
    "SET check_function_bodies = false;",
    "",
  ];

  const body = [];
  let currentSection = null;
  for (const row of sorted) {
    if (row.section !== currentSection) {
      currentSection = row.section;
      body.push("", `-- ${"=".repeat(70)}`, `-- ${SECTION_TITLES[row.section]}`, `-- ${"=".repeat(70)}`, "");
    }
    body.push(row.ddl, COMPACT_SECTIONS.has(row.section) ? null : "");
  }

  return `${[...header, ...body.filter((line) => line !== null)].join("\n").trimEnd()}\n`;
}
